/* BALI 2027 · Global click-to-load Google Maps; Street View retains original svLoad click handling.
   Map imagery is illustrative local SVG, not a misleading geographic screenshot. */
(function () {
  "use strict";
  if (window.__baliMapClickPreviewInstalled) return;
  window.__baliMapClickPreviewInstalled = true;
  function isMapUrl(value) {
    return /^https:\/\/(?:www\.)?(?:maps\.google\.com\/maps|google\.com\/maps)(?:[/?#]|$)/i.test(String(value || "").replace(/&amp;/g, "&"));
  }
  function isStreetView(frame) {
    return !!(frame.closest && frame.closest(".sv-stage")) || frame.title === "Google Street View";
  }
  var originalSetAttribute = Element.prototype.setAttribute;
  var iframeSrc = Object.getOwnPropertyDescriptor(HTMLIFrameElement.prototype, "src");
  function store(frame, value) {
    originalSetAttribute.call(frame, "data-bali-map-src", String(value));
  }
  // Intercept dynamically updated route iframes, including those generated by older scripts.
  if (iframeSrc && iframeSrc.configurable && iframeSrc.set) {
    Object.defineProperty(HTMLIFrameElement.prototype, "src", {
      configurable: true, enumerable: iframeSrc.enumerable,
      get: function () {
        return this.getAttribute("data-bali-map-active") === "1" || !this.hasAttribute("data-bali-map-src")
          ? iframeSrc.get.call(this)
          : this.getAttribute("data-bali-map-src");
      },
      set: function (value) {
        if (isMapUrl(value) && !isStreetView(this) && this.getAttribute("data-bali-map-active") !== "1") {
          store(this, value);
          return;
        }
        iframeSrc.set.call(this, value);
      }
    });
  }
  Element.prototype.setAttribute = function (name, value) {
    if (this instanceof HTMLIFrameElement && String(name).toLowerCase() === "src" &&
        isMapUrl(value) && !isStreetView(this) && this.getAttribute("data-bali-map-active") !== "1") {
      store(this, value);
      return;
    }
    return originalSetAttribute.call(this, name, value);
  };
  function labelFor(frame) {
    var title = frame.getAttribute("title") || "";
    var region = frame.closest(".hotel-location-map");
    if (region) return region.getAttribute("aria-label") || title || "Poloha hotelu";
    var head = frame.parentElement && frame.parentElement.querySelector(".map-title,.map-heading,h3,h4,strong");
    return head ? head.textContent.trim().slice(0,110) : (title || "Mapa trasy a okolí");
  }
  function decorate(frame) {
    if (!frame || !frame.isConnected || isStreetView(frame)) return;
    var existingSrc = frame.getAttribute("src");
    if (!frame.hasAttribute("data-bali-map-src") && isMapUrl(existingSrc)) {
      store(frame, existingSrc);
      frame.removeAttribute("src");
    }
    if (!frame.hasAttribute("data-bali-map-src") || frame.getAttribute("data-bali-map-active") === "1") return;
    if (frame.previousElementSibling && frame.previousElementSibling.classList.contains("bali-map-preview")) return;
    var button = document.createElement("button");
    button.type = "button";
    button.className = "bali-map-preview";
    button.setAttribute("aria-label", "Spustit interaktivní Google mapu: " + labelFor(frame));
    var title = document.createElement("span");
    title.className = "bali-map-preview-title";
    title.textContent = labelFor(frame);
    var call = document.createElement("span");
    call.className = "bali-map-preview-label";
    call.textContent = "▶ Spustit interaktivní mapu";
    button.append(title, call);
    button.addEventListener("click", function (event) {
      event.preventDefault();
      event.stopPropagation();
      var src = frame.getAttribute("data-bali-map-src");
      if (!src || !isMapUrl(src)) return;
      originalSetAttribute.call(frame, "data-bali-map-active", "1");
      frame.setAttribute("loading", "eager");
      frame.setAttribute("src", src);
      button.remove();
    });
    frame.parentNode.insertBefore(button, frame);
  }
  function scan(root) {
    if (!root) return;
    if (root.tagName === "IFRAME") decorate(root);
    if (root.querySelectorAll) root.querySelectorAll("iframe").forEach(decorate);
  }
  function init() {
    scan(document);
    if (!window.MutationObserver) return;
    var pending = false;
    var observer = new MutationObserver(function (records) {
      if (pending) return;
      if (!records.some(function (record) {
        return Array.prototype.some.call(record.addedNodes || [], function (node) {
          return node.nodeType === 1 && (node.tagName === "IFRAME" || (node.querySelector && node.querySelector("iframe")));
        });
      })) return;
      pending = true;
      requestAnimationFrame(function () { pending = false; scan(document); });
    });
    observer.observe(document.body, { childList:true, subtree:true });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init, { once:true });
  else init();
})();
