    function updateAllMaps() {
        // Lombok Map Update
        const iframeLombok = document.getElementById('lombokPortReturnMapFrame');
        const titleElLombok = document.getElementById('lombokPortReturnMapTitle');
        const noteSpanLombok = document.getElementById('lombokPortReturnNote');
        if (iframeLombok) {
            const deckHtml = document.getElementById('selectedHotelsDeck')?.innerHTML || '';
            const isLocalActive = deckHtml.includes('AreGuling') || deckHtml.includes('Are Guling') || deckHtml.includes('TheLocal');
            let hotelName = 'El Tropico Boutique Hotel';
            let targetUrl = hotelToPortTropico;
            if (isLocalActive) {
                hotelName = 'TheLocal AreGuling';
                targetUrl = hotelToPortLocal;
            }
            if (iframeLombok.src !== targetUrl) iframeLombok.src = targetUrl;
            const dynamicText = `📍 Trasa z hotelu (${hotelName}) do přístavu na Lomboku`;
            if (titleElLombok) titleElLombok.textContent = dynamicText;
            if (noteSpanLombok) noteSpanLombok.textContent = dynamicText;
        }

        // Bali Hotel Map Update
        const iframeBali = document.getElementById('baliReturnHotelMapFrame');
        const titleElBali = document.getElementById('baliReturnHotelMapTitle');
        const noteSpanBali = document.getElementById('baliReturnHotelNote');
        if (iframeBali) {
            const deckHtml = document.getElementById('selectedHotelsDeck')?.innerHTML || '';
            const isBakungActive = deckHtml.includes('Bakung Beach') || deckHtml.includes('Bakung');
            const isBaliSandyActive = deckHtml.includes('Bali Sandy') || deckHtml.includes('Bali Sandy Resort');
            let hotelName = 'Grand Ixora Kuta Resort';
            let targetUrl = portToGrandIxora;
            if (isBakungActive) {
                hotelName = 'Bakung Beach Resort';
                targetUrl = portToBakung;
            } else if (isBaliSandyActive) {
                hotelName = 'Bali Sandy Resort';
                targetUrl = portToBaliSandy;
            }
            if (iframeBali.src !== targetUrl) iframeBali.src = targetUrl;
            const dynamicTextBali = `📍 Trasa z přístavu Sanur do hotelu (${hotelName}) na Bali`;
            if (titleElBali) titleElBali.textContent = dynamicTextBali;
            if (noteSpanBali) noteSpanBali.textContent = dynamicTextBali;
        }

        // Airport Map Update
        const iframeAirport = document.getElementById('baliAirportMapFrame');
        const titleElAirport = document.getElementById('baliAirportMapTitle');
        const noteSpanAirport = document.getElementById('baliAirportNote');
        if (iframeAirport) {
            const deckHtml = document.getElementById('selectedHotelsDeck')?.innerHTML || '';
            const isBakungActive = deckHtml.includes('Bakung Beach') || deckHtml.includes('Bakung');
            const isBaliSandyActive = deckHtml.includes('Bali Sandy Resort') || deckHtml.includes('Bali Sandy');
            let hotelName = 'Grand Ixora Kuta Resort';
            let targetUrl = hotelToAirportIxora;
            if (isBakungActive) {
                hotelName = 'Bakung Beach Resort';
                targetUrl = hotelToAirportBakung;
            } else if (isBaliSandyActive) {
                hotelName = 'Bali Sandy Resort';
                targetUrl = hotelToAirportBaliSandy;
            }
            if (iframeAirport.src !== targetUrl) iframeAirport.src = targetUrl;
            const dynamicTextAirport = `📍 Trasa z hotelu (${hotelName}) na letiště Bali`;
            if (titleElAirport) titleElAirport.textContent = dynamicTextAirport;
            if (noteSpanAirport) noteSpanAirport.textContent = dynamicTextAirport;
        }
    }

    document.addEventListener('DOMContentLoaded', () => {
        const deck = document.getElementById('selectedHotelsDeck');
        if (deck) {
            const observer = new MutationObserver(updateAllMaps);
            observer.observe(deck, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ['class'] });
        }
        updateAllMaps();
    });

    setTimeout(updateAllMaps, 50);

